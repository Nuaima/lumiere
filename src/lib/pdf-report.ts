import { jsPDF } from "jspdf";
import type { BeautyProfile } from "./beauty-store";
import { monk } from "./monk";

export function exportSkinReport(profile: BeautyProfile) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 48;
  let y = M;

  // Header bar
  doc.setFillColor(184, 84, 64);
  doc.rect(0, 0, W, 8, "F");

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(26);
  doc.setTextColor(33, 25, 22);
  doc.text("Lumière", M, (y += 28));
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(120, 110, 105);
  doc.text("AI Beauty Intelligence Report", M, (y += 14));
  doc.text(new Date(profile.createdAt).toLocaleString(), W - M, y, { align: "right" });

  y += 24;
  doc.setDrawColor(230, 220, 215);
  doc.line(M, y, W - M, y);
  y += 24;

  // Selfie
  try { doc.addImage(profile.imageDataUrl, "JPEG", M, y, 130, 130); } catch { /* */ }

  // Profile summary block
  const xRight = M + 150;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(33, 25, 22);
  doc.text("Your Skin Profile", xRight, y + 16);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(80, 75, 72);
  const monkSwatch = monk(profile.monkTone);
  const rows: [string, string][] = [
    ["Monk Skin Tone", `${monkSwatch.label} (${monkSwatch.hex})`],
    ["Undertone", profile.undertone],
    ["Skin Type", profile.skinType],
    ["Recommended Shade", profile.shadeFamily],
    ["Concerns", profile.conditions.join(", ") || "—"],
    ["Analysis Confidence", `${profile.confidence}%`],
    ["Source", profile.source === "ai" ? "Lumière AI Vision" : "Offline estimate"],
  ];
  let ry = y + 34;
  rows.forEach(([k, v]) => {
    doc.setTextColor(150, 140, 135);
    doc.text(k, xRight, ry);
    doc.setTextColor(33, 25, 22);
    doc.text(String(v), xRight + 130, ry);
    ry += 14;
  });

  // Monk swatch
  doc.setFillColor(monkSwatch.hex);
  doc.rect(xRight + 270, y + 24, 28, 28, "F");

  y += 160;

  // Scores
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(33, 25, 22);
  doc.text("Skin Health Scores", M, y);
  y += 14;
  const scores: [string, number][] = [
    ["Hydration", profile.hydration],
    ["Evenness", profile.evenness],
    ["Radiance", profile.radiance],
  ];
  scores.forEach(([k, v]) => {
    doc.setFontSize(10);
    doc.setTextColor(80, 75, 72);
    doc.text(k, M, (y += 18));
    doc.text(`${v}/100`, W - M, y, { align: "right" });
    doc.setFillColor(240, 232, 226);
    doc.rect(M, y + 4, W - 2 * M, 6, "F");
    doc.setFillColor(184, 84, 64);
    doc.rect(M, y + 4, ((W - 2 * M) * v) / 100, 6, "F");
    y += 12;
  });

  y += 24;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(33, 25, 22);
  doc.text("Personalized Analysis", M, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(80, 75, 72);
  const lines = doc.splitTextToSize(profile.summary, W - 2 * M);
  doc.text(lines, M, (y += 4));
  y += lines.length * 12 + 18;

  // Routines (two columns)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(33, 25, 22);
  doc.text("AM Routine", M, y);
  doc.text("PM Routine", W / 2 + 8, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(80, 75, 72);
  const maxLen = Math.max(profile.amRoutine.length, profile.pmRoutine.length);
  for (let i = 0; i < maxLen; i++) {
    const am = profile.amRoutine[i] ?? "";
    const pm = profile.pmRoutine[i] ?? "";
    if (am) doc.text(`${i + 1}. ${am}`, M, y);
    if (pm) doc.text(`${i + 1}. ${pm}`, W / 2 + 8, y);
    y += 14;
  }

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(160, 150, 145);
  doc.text(
    "This report is generated by Lumière AI and is for cosmetic guidance only. Not medical advice.",
    M,
    doc.internal.pageSize.getHeight() - 24
  );

  doc.save(`lumiere-skin-report-${new Date(profile.createdAt).toISOString().slice(0, 10)}.pdf`);
}
